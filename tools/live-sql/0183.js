// What it changes in place: only the stage test, from WAS to NOW.
const PATCHES = [['0168', 'store_live', 'store_live(uuid)'], ['0164', 'store_money_holds', 'store_money_holds(uuid)']];
const WAS = "q.status = 'preparing' and not coalesce(q.voided, false) and not coalesce(q.invoiced, false)";
const NOW = "(q.status = 'preparing' or ow_ready_to_collect(q.status, q.payload)) and not coalesce(q.voided, false) and not coalesce(q.invoiced, false)";
// What it leans on, unchanged: their push keys are taken first.
const LEANS = [['0177', 'cancel_order', 'cancel_order(uuid, bigint, text, text, text)'], ['0131', 'invoice_asks_ow_push2', 'invoice_asks_ow_push2()']];
// What it makes.
const OWN = [
  ['ow_ready_to_collect', 'ow_ready_to_collect(text, jsonb)'],
  ['saved_quotes_ow_a_yard_push', 'saved_quotes_ow_a_yard_push()'],
  ['stock_counts_ow_push', 'stock_counts_ow_push()'],
  ['invoice_asks_ow_a_yard_push', 'invoice_asks_ow_a_yard_push()'],
];

const IN = `(to_regprocedure('ow_ready_to_collect(text, jsonb)') is not null
         and exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_a_yard_push')
         and exists (select 1 from pg_trigger where tgname = 'stock_counts_ow_push')
         and exists (select 1 from pg_trigger where tgname = 'invoice_asks_ow_a_yard_push'))`;

const q = (s) => s.replace(/'/g, "''");
// A function's body in this database, read as ctx.fingerprint reads a migration's.
const fp = (sig) => `(select md5(translate(p.prosrc, chr(32) || chr(9) || chr(13) || chr(10), '')) from pg_proc p where p.oid = to_regprocedure('${sig}'))`;
// The same, with 0183's change undone (a function 0183 changed in place, read as it was).
const fpUndone = (sig) => `(select md5(translate(replace(replace(p.prosrc, chr(13), ''), '${q(NOW)}', '${q(WAS)}'), chr(32) || chr(9) || chr(13) || chr(10), '')) from pg_proc p where p.oid = to_regprocedure('${sig}'))`;

