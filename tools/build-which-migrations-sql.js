#!/usr/bin/env node
'use strict';
/*
 * A read-only query for the live SQL editor: which of the repo's
 * migrations are in this database.
 *
 * The live project was built by pasting migrations by hand, so nothing
 * there records which ran. Each migration leaves things behind, though:
 * the functions, triggers and tables it creates and the columns it adds.
 * This lists them per migration (from the files, comments stripped; an
 * object a later migration drops is not counted) and asks the database for
 * each. A migration is "in" when all of its marks are there, "missing" when
 * none are, "partly" when some are (a later migration changed it, or it
 * stopped half-way), and "cannot tell" when it leaves no mark of its own
 * (it only changes data or rewrites a function in place).
 *
 * docs/live/which-migrations.sql is this tool's output, committed;
 * test/live-apply-0171-0177.test.js checks it against the tool and runs it.
 *
 * Run: node tools/build-which-migrations-sql.js [out.sql]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'supabase/migrations');
const files = fs.readdirSync(DIR).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();

const strip = (s) => s.replace(/--[^\n]*/g, '');
const marks = files.map((f) => {
  const sql = strip(fs.readFileSync(path.join(DIR, f), 'utf8'));
  const out = [];
  for (const m of sql.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?([a-z_0-9]+)\s*\(/gi)) out.push(['function', m[1].toLowerCase(), '']);
  for (const m of sql.matchAll(/create\s+(?:constraint\s+)?trigger\s+([a-z_0-9]+)/gi)) out.push(['trigger', m[1].toLowerCase(), '']);
  for (const m of sql.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?([a-z_0-9]+)/gi)) out.push(['table', m[1].toLowerCase(), '']);
  for (const m of sql.matchAll(/alter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?(?:public\.)?([a-z_0-9]+)\s+add\s+column\s+(?:if\s+not\s+exists\s+)?([a-z_0-9]+)/gi)) out.push(['column', m[1].toLowerCase(), m[2].toLowerCase()]);
  return { f, sql, out };
});
// Dropped by a later migration: not a mark of the one that made it.
const droppedAfter = (i, kind, name, col) => marks.slice(i + 1).some(({ sql }) => kind === 'column'
  ? new RegExp(`alter\\s+table\\s+(?:if\\s+exists\\s+)?(?:only\\s+)?(?:public\\.)?${name}\\s+drop\\s+column\\s+(?:if\\s+exists\\s+)?${col}\\b`, 'i').test(sql)
  : new RegExp(`drop\\s+${kind}\\s+(?:if\\s+exists\\s+)?(?:public\\.)?${name}\\b`, 'i').test(sql));
// Made by an earlier migration first: then it marks that one, not this.
const madeBefore = (i, kind, name, col) => marks.slice(0, i).some(({ out }) => out.some(([k, n, c]) => k === kind && n === name && c === col));

const rows = [];
marks.forEach(({ f, out }, i) => {
  const seen = new Set();
  out.forEach(([kind, name, col]) => {
    const k = kind + ':' + name + ':' + col;
    if (seen.has(k) || madeBefore(i, kind, name, col) || droppedAfter(i, kind, name, col)) return;
    seen.add(k);
    rows.push(`('${f.slice(0, 4)}', '${f.replace(/\.sql$/, '')}', '${kind}', '${name}', '${col}')`);
  });
  if (!seen.size) rows.push(`('${f.slice(0, 4)}', '${f.replace(/\.sql$/, '')}', 'none', '', '')`);
});

const text = `-- =====================================================================
-- Which of the repo's migrations are in this database (read-only).
-- GENERATED by tools/build-which-migrations-sql.js from supabase/migrations.
-- Do not edit by hand: run the tool again after adding a migration.
--
-- Paste into the SQL editor and run. It changes nothing. One row per
-- migration that is not fully in: "missing" (none of what it first makes
-- is here) or "partly" (some is). The first row counts the ones fully in,
-- and the ones that make nothing of their own to look for.
-- =====================================================================
with m(no, migration, kind, name, col) as (values
  ${rows.join(',\n  ')}
), found as (
  select no, migration, kind, name, col,
         case kind
           when 'function' then exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = m.name)
           when 'trigger'  then exists (select 1 from pg_trigger t where not t.tgisinternal and t.tgname = m.name)
           when 'table'    then to_regclass('public.' || m.name) is not null
           when 'column'   then exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = m.name and c.column_name = m.col)
         end as here
    from m
), per as (
  select no, migration,
         case when bool_and(kind = 'none') then 'cannot tell'
              when bool_and(here) then 'in'
              when bool_or(here) then 'partly'
              else 'missing' end as status,
         count(*) filter (where here) || ' of ' || count(*) filter (where kind <> 'none') as marks_found,
         string_agg(case when not here then kind || ' ' || name || case when col <> '' then '.' || col else '' end end, ', ' order by kind, name) as not_found
    from found group by no, migration
)
select migration, status, marks_found, not_found from per where status in ('missing', 'partly')
union all
select '(' || count(*) filter (where status = 'in') || ' migrations fully in; ' || count(*) filter (where status = 'cannot tell')
       || ' leave nothing to look for)', null, null, null from per
order by 1;
`;
const dest = process.argv[2];
if (dest) fs.writeFileSync(dest, text); else process.stdout.write(text);
