#!/usr/bin/env node
'use strict';
/*
 * What the live database was found missing on 28 Oct 2026, before the
 * rebuild's fixes (docs/live/which-migrations.sql, run on live):
 *
 *   0120  partly: push_outbox.claimed_at and .delivered, and ow_push_claim
 *         (push-send claims its rows with it, so two calls never send one
 *         push twice). The rest of 0120 is there, and later migrations
 *         changed it (0131, 0167, 0174), so 0120 is NOT run again whole:
 *         only these pieces, cut from its file.
 *   0153  missing: the push to the Manager when a dearer supplier price
 *         puts a line under its sale. Whole; nothing later redefines it.
 *   0158  missing: refuse_restock_buy, tell_customer_change (the Manager
 *         app calls both) and the job.given push. Whole; nothing later
 *         redefines it.
 *
 * Writes docs/live/catch-up-before-0171.sql: a read-only prerequisites
 * step, then the three as one transaction, then a read-only check.
 * test/live-apply-0171-0177.test.js runs it on a database made to look
 * like live did.
 *
 * Run: node tools/build-catch-up-sql.js [out.sql]
 */
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'supabase/migrations');
const file = (no) => fs.readdirSync(DIR).find((f) => f.startsWith(no + '_'));
const text = (no) => fs.readFileSync(path.join(DIR, file(no)), 'utf8');

// 0120's missing pieces, cut from its file so they never drift from it.
const m120 = text('0120');
const piece = (from, to) => {
  const a = m120.indexOf(from), b = m120.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`0120 no longer has: ${from}`);
  return m120.slice(a, b + to.length);
};
const cols = piece('alter table push_outbox add column if not exists claimed_at timestamptz;', "alter table push_outbox add column if not exists delivered bigint[] not null default '{}';");
const idx = piece('create index if not exists push_outbox_unsent_idx', ';');
const claim = piece('create or replace function ow_push_claim(p_limit int)', 'grant execute on function ow_push_claim(int) to service_role;');

const out = `-- =====================================================================
-- Catch-up for the LIVE shop, before the rebuild's fixes (0171-0177).
-- GENERATED by tools/build-catch-up-sql.js from supabase/migrations. Do
-- not edit by hand.
--
-- docs/live/which-migrations.sql, run on live on 28 Oct 2026, found:
--   0120  partly: push_outbox.claimed_at, push_outbox.delivered, ow_push_claim
--   0153  missing (the push when a dearer supplier price puts a line under its sale)
--   0158  missing (the Manager's "no" to a carton, telling Sales a customer
--         changed, the job.given push to a driver)
-- 0120 is not run again whole (later migrations changed it): only its
-- three missing pieces. 0153 and 0158 go in whole.
--
-- How to run it, in the live project's SQL editor:
--   1. STEP 1 alone. It changes nothing; if it stops, do not go on.
--   2. STEP 2, from BEGIN to COMMIT, in one go: all of it, or none.
--      Safe to run twice.
--   3. STEP 3. Every row says ok. Then run which-migrations.sql again:
--      it should name only 0171, 0173, 0174, 0175, 0176 and 0177.
--   4. Then docs/live/apply-0171-0177.sql, from its step 1.
-- =====================================================================

-- =====================================================================
-- STEP 1  PREREQUISITES (read-only)
-- =====================================================================
do $pre$
declare missing text[] := '{}';
begin
  if to_regclass('public.push_outbox') is null or to_regprocedure('ow_push(uuid, text, text, text, uuid, text, text, jsonb, text)') is null
     or to_regprocedure('ow_uuid(text)') is null or to_regprocedure('ow_money(numeric)') is null then missing := missing || '0120'::text; end if;
  if to_regprocedure('ow_line_sell_price(uuid, jsonb, jsonb)') is null or to_regprocedure('ow_num(text)') is null then missing := missing || '0119'::text; end if;
  if to_regprocedure('ow_first_name(uuid, uuid)') is null then missing := missing || '0131'::text; end if;
  if to_regprocedure('hold_restock_buy(uuid, boolean)') is null then missing := missing || '0136'::text; end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'restock_buys' and column_name = 'for_line') then missing := missing || '0151'::text; end if;
  if array_length(missing, 1) is not null then
    raise exception 'Not run: % not in this database yet.', array_to_string(missing, ', ');
  end if;
  raise notice 'Ready.';
end $pre$;

-- =====================================================================
-- STEP 2  APPLY: from BEGIN to COMMIT, in one go
-- =====================================================================
begin;
-- ---------------------------------------------------------------------
-- From ${file('0120')}: the pieces live does not have.
-- ---------------------------------------------------------------------
${cols}
${idx}

${claim}

-- ---------------------------------------------------------------------
-- ${file('0153')}
-- ---------------------------------------------------------------------
${text('0153').trim()}

-- ---------------------------------------------------------------------
-- ${file('0158')}
-- ---------------------------------------------------------------------
${text('0158').trim()}
commit;

-- =====================================================================
-- STEP 3  CHECK AFTERWARDS (read-only): every row says ok
-- =====================================================================
select m, case when ok then 'ok' else 'MISSING' end from (values
  ('0120 push_outbox.claimed_at, .delivered', exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'push_outbox' and column_name = 'claimed_at')
                                              and exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'push_outbox' and column_name = 'delivered')),
  ('0120 ow_push_claim',                      to_regprocedure('ow_push_claim(integer)') is not null),
  ('0153 price up, told',                     exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_price_up')),
  ('0158 the Manager''s asks',                to_regprocedure('refuse_restock_buy(uuid)') is not null and to_regprocedure('tell_customer_change(uuid, text, uuid, text)') is not null
                                              and exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_push_job'))
) as t(m, ok);

-- Pushes waiting to go out (read-only). Many unsent rows with an error
-- naming ow_push_claim mean push-send could not claim them before this.
select count(*) filter (where sent_at is null and created_at > now() - interval '1 day') as unsent_last_day,
       count(*) filter (where sent_at is not null and created_at > now() - interval '1 day') as sent_last_day,
       max(created_at) filter (where sent_at is not null) as last_sent
  from push_outbox;
`;
const dest = process.argv[2];
if (dest) fs.writeFileSync(dest, out); else process.stdout.write(out);
