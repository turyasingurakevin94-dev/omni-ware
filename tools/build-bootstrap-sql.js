#!/usr/bin/env node
'use strict';
/*
 * Concatenates every migration into one file that can be pasted into the
 * Supabase dashboard's SQL editor.
 *
 * This exists for people without a terminal. `supabase db push` is the
 * right way to stand a project up and the staging workflow runs it, but
 * `db push` is a CLI, and the CLI is the one thing the graphical path
 * does not have. If it refuses these filenames -- they are `0001_name`,
 * not the 14-digit timestamps the CLI now mints -- there has to be a
 * second way in that needs nothing but a browser and a clipboard.
 *
 * It also writes the bookkeeping rows `db push` would have written, so a
 * project bootstrapped this way is not then a project the CLI wants to
 * apply all 95 migrations to a second time.
 *
 * Output goes to stdout, or to the path given as the first argument.
 *
 * Run: node tools/build-bootstrap-sql.js [out.sql]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'supabase/migrations');

const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.sql')).sort();
if (!files.length) {
  console.error('no migrations found in supabase/migrations');
  process.exit(1);
}

// `0007_price_source.sql` -> version 0007, name price_source. The CLI
// stores the leading digits as the version; keeping the same shape is
// what makes a later `db push` agree that these already ran.
function split(file) {
  const m = /^(\d+)_(.+)\.sql$/.exec(file);
  if (!m) throw new Error(`migration filename is not <digits>_<name>.sql: ${file}`);
  return { version: m[1], name: m[2] };
}

const rule = '-- ' + '-'.repeat(68);
const out = [];

out.push('-- Omni-Ware — every migration, in order, as one script.');
out.push('--');
out.push(`-- Generated by tools/build-bootstrap-sql.js from the ${files.length} files`);
out.push('-- in supabase/migrations/. Do not edit this by hand and do not commit');
out.push('-- it: the migrations are the source, this is a printout of them.');
out.push('--');
out.push('-- Paste into the SQL editor of a NEW, EMPTY project. Running it');
out.push('-- against a project that already has this schema is not what it is');
out.push('-- for, and running it against the live project would be a very bad');
out.push('-- afternoon. Check the project name in the top-left first.');
out.push('');
out.push('begin;');
out.push('');

files.forEach((f) => {
  const { version, name } = split(f);
  out.push(rule);
  out.push(`-- ${version}  ${name.replace(/_/g, ' ')}`);
  out.push(rule);
  out.push(fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\s*$/, ''));
  out.push('');
});

out.push(rule);
out.push('-- Bookkeeping: tell the CLI these already ran, so that linking this');
out.push('-- project later does not replay all of them.');
out.push(rule);
out.push('create schema if not exists supabase_migrations;');
out.push('create table if not exists supabase_migrations.schema_migrations (');
out.push('  version text primary key,');
out.push('  statements text[],');
out.push('  name text');
out.push(');');
out.push('');
out.push('insert into supabase_migrations.schema_migrations (version, name) values');
out.push(files.map((f) => {
  const { version, name } = split(f);
  return `  ('${version}', '${name.replace(/'/g, "''")}')`;
}).join(',\n') + '\non conflict (version) do nothing;');
out.push('');
out.push('commit;');
out.push('');

const text = out.join('\n');
const dest = process.argv[2];
if (dest) {
  fs.writeFileSync(dest, text);
  console.error(`${files.length} migrations -> ${dest} (${text.length} bytes)`);
} else {
  process.stdout.write(text);
}
