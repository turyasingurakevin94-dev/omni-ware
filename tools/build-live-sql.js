#!/usr/bin/env node
'use strict';
/*
 * The rebuild's backend fixes (docs/rebuild.md, "Backend fixes decided"),
 * 0171-0177, as one script for the LIVE project's SQL editor.
 *
 * Migrations reach the live shop as a paste into the Supabase SQL editor,
 * read before they are run (.github/workflows/deploy-functions.yml says
 * so: only edge functions go through Actions, never the database). Seven
 * pastes in the right order, each able to stop half-way, is seven chances
 * to leave the books between two rules. So this writes one script:
 *
 *   STEP 1  PREREQUISITES  read-only. Stops with a plain message if the
 *           live database is missing what the seven are built on (0109 to
 *           0169), or if a function two of them patch is not the shape
 *           they expect. Says which of the seven are in already.
 *   STEP 2  PREVIEW        read-only. What will change for the staff.
 *   STEP 3  APPLY          BEGIN, the seven migrations as they are in
 *           supabase/migrations, COMMIT: all of them, or none.
 *   STEP 4  CHECK AFTERWARDS  read-only.
 *
 * docs/live/apply-0171-0177.sql is this script's output, committed, and
 * test/live-apply-0171-0177.test.js holds the two to each other and runs it
 * on a database made from the migrations.
 *
 * Run: node tools/build-live-sql.js [out.sql]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'supabase/migrations');
const FIRST = 171;
const LAST = 177;

const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.sql')).sort()
  .filter((f) => { const n = Number(f.slice(0, 4)); return n >= FIRST && n <= LAST; });
if (files.length !== LAST - FIRST + 1) {
  console.error(`expected migrations ${FIRST}-${LAST}, found ${files.join(', ')}`);
  process.exit(1);
}

const out = [];
const add = (s) => out.push(s);

add(`-- =====================================================================
-- The rebuild's backend fixes, 0171-0177, for the LIVE shop.
-- GENERATED by tools/build-live-sql.js from supabase/migrations. Do not
-- edit by hand: change the migration, then run the tool again.
--
--   0171  no sale below cost
--   0172  an agent order's total counts its charges
--   0173  moving a stage needs its task
--   0174  the Checking gate checks suppliers' yes, lines with no supplier,
--         agent prepay and old debt
--   0175  the Manager's answers are written only with their task
--   0176  a void and a credit note, one write each
--   0177  one Cancel, by the Manager
--
-- How to run it, in the live project's SQL editor (Omni-ware, ref
-- hgywjaifdmgrcnwxstxg):
--   1. Paste and run STEP 1 alone. It changes nothing. If it stops, it
--      says what is missing; do not go on.
--   2. Run the STEP 2 queries. They change nothing. They list what the
--      staff will notice: tell the Manager before step 3.
--   3. Run STEP 3, from BEGIN to COMMIT, in one go. It is one transaction:
--      if it stops with an error, nothing has changed. Running it a
--      second time is safe.
--   4. Run the STEP 4 queries. Every row should say ok.
-- =====================================================================
`);

add(`-- =====================================================================
-- STEP 1  PREREQUISITES (read-only)
-- =====================================================================
do $pre$
declare
  missing text[] := '{}';
  shape text[] := '{}';
  done text[] := '{}';
  src text;
begin
  if to_regprocedure('public.order_shop_total(jsonb)') is null or to_regprocedure('public.use_agent_credit(uuid, text, bigint, jsonb, timestamptz)') is null
     or to_regprocedure('public.apply_momo_payment(bigint)') is null or to_regprocedure('public.jsonb_num(jsonb)') is null then missing := missing || '0109'::text; end if;
  if to_regprocedure('ow_gate_reason(uuid, jsonb, numeric)') is null or to_regprocedure('ow_line_sell_price(uuid, jsonb, jsonb)') is null
     or to_regprocedure('ow_line_waits_price(uuid, jsonb, jsonb)') is null or to_regprocedure('ow_system_begin()') is null
     or to_regprocedure('ow_today()') is null or to_regprocedure('ow_num(text)') is null
     or not exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_checking_gate') then missing := missing || '0119'::text; end if;
  if to_regprocedure('ow_push(uuid, text, text, text, uuid, text, text, jsonb, text)') is null or to_regprocedure('saved_quotes_ow_push()') is null
     or to_regprocedure('ow_money(numeric)') is null or to_regprocedure('ow_uuid(text)') is null then missing := missing || '0120'::text; end if;
  if to_regprocedure('saved_quotes_sales_guard()') is null or to_regprocedure('manager_stock_move(uuid, jsonb, text, text, text)') is null
     or to_regprocedure('manager_log_decision(uuid, text, text, numeric, jsonb, jsonb, jsonb)') is null then missing := missing || '0122'::text; end if;
  if to_regprocedure('decide_invoice_ask(uuid, text)') is null or to_regclass('public.invoice_asks') is null then missing := missing || '0123'::text; end if;
  if to_regprocedure('has_task(uuid, text)') is null then missing := missing || '0127'::text; end if;
  if to_regprocedure('ow_reserve_row_ids(uuid, text, bigint, integer)') is null or to_regprocedure('ow_next_row_id(uuid, text, bigint)') is null then missing := missing || '0138'::text; end if;
  if to_regprocedure('ow_line_under_cost(uuid, jsonb, jsonb)') is null then missing := missing || '0153'::text; end if;
  if to_regprocedure('ow_member_name(uuid, uuid)') is null then missing := missing || '0164'::text; end if;
  if to_regprocedure('ow_order_total(uuid, jsonb, boolean)') is null or to_regprocedure('ow_patch_order(uuid, bigint, jsonb, text, text, text[], text)') is null
     or not exists (select 1 from pg_trigger where tgname = 'saved_quotes_zz_money_check') then missing := missing || '0165'::text; end if;
  if to_regprocedure('void_with_money(uuid, bigint, text, text)') is null or to_regprocedure('ow_end_targets(uuid)') is null then missing := missing || '0169'::text; end if;
  if to_regclass('public.collection_trips') is null or to_regclass('public.agents') is null or to_regclass('public.customer_debt_log') is null then missing := missing || 'tables'::text; end if;
  if to_regprocedure('trim_scale(numeric)') is null then missing := missing || 'Postgres 13 or newer'::text; end if;
  if array_length(missing, 1) is not null then
    raise exception 'Not run: % not in this database yet. Run them first, in order, then this.', array_to_string(missing, ', ');
  end if;

  -- The functions 0174 and 0177 change in place must be as 0167 and 0122 left them (or already changed);
  -- line ends are read without the carriage return a paste from Windows leaves.
  src := replace(pg_get_functiondef('public.saved_quotes_ow_push()'::regprocedure), chr(13), '');
  if position('ow_oldest_debt_days' in src) = 0 and position('else '' · no limit set'' end' in src) = 0 then shape := shape || 'saved_quotes_ow_push (0167''s credit.hold wording)'::text; end if;
  src := replace(pg_get_functiondef('saved_quotes_sales_guard()'::regprocedure), chr(13), '');
  if position('order.cancel' in src) = 0 and (position('    if has_task(new.shop_id, ''invoice.void'') then' || chr(10) || '      v_task := ''invoice.void'';' in src) = 0
       or position('case when v_task = ''agent.change'' then ''Closed an agent''''s cancelled order #'' else ''Voided order #'' end' in src) = 0) then
    shape := shape || 'saved_quotes_sales_guard (0122''s void guard)'::text;
  end if;
  if array_length(shape, 1) is not null then
    raise exception 'Not run: % changed since its migration. Compare it with the repo before going on.', array_to_string(shape, '; ');
  end if;

  if exists (select 1 from pg_trigger where tgname = 'saved_quotes_zz_cost_floor') then done := done || '0171'::text; end if;
  if position('p -> ''charges''' in pg_get_functiondef('public.order_shop_total(jsonb)'::regprocedure)) > 0 then done := done || '0172'::text; end if;
  if exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_a_stage_move') then done := done || '0173'::text; end if;
  if to_regprocedure('ow_oldest_debt_days(uuid, text)') is not null then done := done || '0174'::text; end if;
  if exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_a_decisions') then done := done || '0175'::text; end if;
  if to_regprocedure('raise_credit_note(uuid, bigint, jsonb, text, boolean, uuid)') is not null then done := done || '0176'::text; end if;
  if to_regprocedure('cancel_order(uuid, bigint, text, text, text)') is not null then done := done || '0177'::text; end if;
  raise notice 'Ready. Already in: %. Step 3 is safe to run either way.',
    coalesce(nullif(array_to_string(done, ', '), ''), 'none of 0171-0177');
end $pre$;
`);

add(`-- =====================================================================
-- STEP 2  PREVIEW (read-only): what the staff will notice
-- =====================================================================
-- a) Open orders with a line typed under its cost (0171): they cannot be
--    invoiced until the Manager prices them at or above cost, or gives the
--    line away. The hourly run tells the Manager.
select q.id as order_no, q.client_name, q.status, e ->> 'productName' as item,
       (e ->> 'sellPrice')::numeric as sells_at, (e ->> 'price')::numeric as costs
  from saved_quotes q, jsonb_array_elements(case when jsonb_typeof(q.payload -> 'items') = 'array' then q.payload -> 'items' else '[]'::jsonb end) e
 where not q.invoiced and not q.voided and jsonb_typeof(e) = 'object'
   and coalesce(btrim(e -> 'givenAway' ->> 'why'), '') = ''
   and (e ->> 'qty') ~ '^[0-9.]+$' and (e ->> 'qty')::numeric > 0
   and (e ->> 'price') ~ '^[0-9.]+$' and (e ->> 'sellPrice') ~ '^[0-9.]+$'
   and (e ->> 'sellPrice')::numeric > 0 and (e ->> 'sellPrice')::numeric < (e ->> 'price')::numeric
 order by q.id;

-- b) Orders in Checking with a supplier who has not said yes (0174): the
--    Manager's "next" will keep them in Checking until the Buyer has the yes.
select q.id as order_no, q.client_name, count(distinct e ->> 'supplierId') as suppliers_without_a_yes
  from saved_quotes q, jsonb_array_elements(case when jsonb_typeof(q.payload -> 'items') = 'array' then q.payload -> 'items' else '[]'::jsonb end) e
 where q.status = 'draft' and not q.voided and jsonb_typeof(e) = 'object'
   and coalesce(e ->> 'supplierId', '') not in ('', '__stock__')
   and coalesce(q.payload -> 'supplierConfirms' -> (e ->> 'supplierId') ->> 'state', '') <> 'confirmed'
 group by q.id, q.client_name order by q.id;

-- c) Customers with a charge older than 21 days still on their balance (0174):
--    their next order that adds to the debt waits for the Manager's Release.
--    (Step 4 lists it exactly; this is the quick look.)
select c.id, c.name, c.debt, min(l.date) as oldest_charge
  from customers c join customer_debt_log l on l.shop_id = c.shop_id and l.customer_id = c.id and l.type = 'charge'
 where c.debt > 0 and l.date < (now() at time zone 'Africa/Kampala')::date - 21
 group by c.id, c.name, c.debt order by min(l.date);
`);

add(`-- =====================================================================
-- STEP 3  APPLY: from BEGIN to COMMIT, in one go
-- =====================================================================
begin;
`);
for (const f of files) {
  add(`-- ---------------------------------------------------------------------
-- ${f}
-- ---------------------------------------------------------------------
${fs.readFileSync(path.join(DIR, f), 'utf8').trim()}
`);
}
add(`commit;
`);

add(`-- =====================================================================
-- STEP 4  CHECK AFTERWARDS (read-only): every row says ok
-- =====================================================================
select m, case when ok then 'ok' else 'MISSING' end from (values
  ('0171 no sale below cost',            exists (select 1 from pg_trigger where tgname = 'saved_quotes_zz_cost_floor')),
  ('0172 agent total counts charges',    order_shop_total('{"items":[{"sellPrice":1000,"qty":2}],"charges":[{"type":"fixed","value":5000},{"type":"percent","value":10}]}') = 7200),
  ('0173 moving a stage needs its task', exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_a_stage_move')),
  ('0174 the Checking gate checks',      to_regprocedure('ow_oldest_debt_days(uuid, text)') is not null and position('ow_oldest_debt_days' in pg_get_functiondef('public.saved_quotes_ow_push()'::regprocedure)) > 0),
  ('0175 the Manager''s answers',        exists (select 1 from pg_trigger where tgname = 'saved_quotes_ow_a_decisions')),
  ('0176 void and credit note',          to_regprocedure('void_invoice(uuid, bigint, text, boolean, text, text, uuid)') is not null and to_regprocedure('raise_credit_note(uuid, bigint, jsonb, text, boolean, uuid)') is not null),
  ('0177 one Cancel',                    to_regprocedure('cancel_order(uuid, bigint, text, text, text)') is not null and exists (select 1 from role_tasks where role = 'manager' and task = 'order.cancel')
                                         and position('order.cancel' in pg_get_functiondef('saved_quotes_sales_guard()'::regprocedure)) > 0
                                         and position('order.cancel' in pg_get_functiondef('saved_quotes_stage_move()'::regprocedure)) > 0)
) as t(m, ok);

-- What holds each order in Checking now (price, credit, suppliers, unsourced, prepay):
select id as order_no, client_name, ow_gate_reason(shop_id, payload, amount_paid) as waits_for
  from saved_quotes where status = 'draft' and not voided order by id desc limit 50;
`);

const text = out.join('\n');
const dest = process.argv[2];
if (dest) fs.writeFileSync(dest, text); else process.stdout.write(text);
